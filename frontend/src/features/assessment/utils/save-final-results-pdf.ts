import type { FinalResult } from "../api/final-results-api";
import type { Student } from "@/features/student-registration/api/student-registration-api";
import type { GradeDocumentContext } from "./save-student-session-grades-pdf";
import { addAcademicDocumentFooters, drawAcademicDocumentClosing, drawAcademicDocumentHeader, drawAcademicTableHeader, drawAcademicTableRow } from "./academic-document-pdf";

const resultText = (result: FinalResult) => result.resultStatus ? `${result.finalGrade?.toFixed(2) ?? "-"} ${result.resultStatus}` : "Pending";

function listDocumentHeader(pdf: import("jspdf").jsPDF, title: string, context: GradeDocumentContext, reference: string, pageWidth: number) {
  const right = pageWidth - 14;
  const center = pageWidth / 2;
  pdf.setProperties({ author: "Universite Ibn Zohr", creator: "University Management Platform", subject: title, title });
  pdf.setFillColor(18, 91, 145);
  pdf.rect(0, 0, pageWidth, 5, "F");
  pdf.setFillColor(18, 91, 145);
  pdf.roundedRect(14, 10, 17, 14, 1.5, 1.5, "F");
  pdf.setTextColor(255, 255, 255);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(10);
  pdf.text("UIZ", 22.5, 18.8, { align: "center" });
  pdf.setTextColor(23, 58, 85);
  pdf.setFontSize(12);
  pdf.text("UNIVERSITE IBN ZOHR", 36, 15);
  pdf.setFont("helvetica", "normal");
  pdf.setTextColor(94, 113, 130);
  pdf.setFontSize(7.5);
  pdf.text("ACADEMIC ADMINISTRATION", 36, 20);
  pdf.setFontSize(7);
  pdf.text("DOCUMENT REFERENCE", right, 14, { align: "right" });
  pdf.setTextColor(23, 58, 85);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(8);
  pdf.text(reference, right, 19, { align: "right" });
  pdf.setDrawColor(198, 211, 222);
  pdf.line(14, 30, right, 30);
  pdf.setFontSize(15);
  pdf.text(title.toUpperCase(), center, 42, { align: "center" });
  pdf.setFillColor(18, 91, 145);
  pdf.rect(center - 14, 46, 28, 0.8, "F");
  pdf.setTextColor(94, 113, 130);
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(8.5);
  pdf.text(context.label, center, 53, { align: "center", maxWidth: pageWidth - 40 });

  const fields = [
    ["Filiere", context.program], ["Path", context.programPath], ["Level", context.academicLevel],
    ["Semester", context.semester], ["Academic year", context.academicYear],
  ].filter((field): field is [string, string] => Boolean(field[1]));
  const fieldWidth = (pageWidth - 28) / Math.max(fields.length, 1);
  fields.forEach(([label, value], index) => {
    const x = 14 + index * fieldWidth;
    pdf.setTextColor(94, 113, 130);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(7);
    pdf.text(label.toUpperCase(), x, 66);
    pdf.setTextColor(23, 58, 85);
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(8.5);
    pdf.text(value, x, 72, { maxWidth: fieldWidth - 5 });
  });
  pdf.setDrawColor(198, 211, 222);
  pdf.line(14, 79, right, 79);
}

function listDocumentFooters(pdf: import("jspdf").jsPDF, pageWidth: number, pageHeight: number) {
  const pages = pdf.getNumberOfPages();
  for (let page = 1; page <= pages; page += 1) {
    pdf.setPage(page);
    pdf.setDrawColor(198, 211, 222);
    pdf.line(14, pageHeight - 13, pageWidth - 14, pageHeight - 13);
    pdf.setTextColor(94, 113, 130);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(6.8);
    pdf.text("Official academic record generated by the Universite Ibn Zohr management platform.", 14, pageHeight - 8);
    pdf.text(`Page ${page} / ${pages}`, pageWidth - 14, pageHeight - 8, { align: "right" });
  }
}

export async function saveModuleFinalResultsPdf(results: FinalResult[], context: GradeDocumentContext) {
  if (!results.length) return;
  const { jsPDF } = await import("jspdf");
  const module = results[0];
  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  listDocumentHeader(pdf, "Module Final Result Sheet", context, `MR-${module.subjectModuleCode}-${new Date().getFullYear()}`, 210);
  pdf.setTextColor(23, 58, 85);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(10);
  pdf.text(`${module.subjectModuleCode}  |  ${module.subjectModuleTitle}`, 14, 88);
  const widths = [10, 65, 31, 24, 25, 28];
  const labels = ["No.", "Student", "Apogee", "Inscription", "Grade", "Result"];
  let y = 94;
  const drawHeader = () => {
    pdf.setFillColor(23, 58, 85);
    pdf.rect(14, y, 183, 9, "F");
    pdf.setTextColor(255, 255, 255);
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(7.5);
    let x = 14;
    labels.forEach((label, index) => { pdf.text(label.toUpperCase(), x + 1.5, y + 5.8); x += widths[index]; });
    y += 9;
  };
  drawHeader();
  results.forEach((result, index) => {
    if (y > 266) { pdf.addPage(); listDocumentHeader(pdf, "Module Final Result Sheet", context, `MR-${module.subjectModuleCode}-${new Date().getFullYear()}`, 210); y = 88; drawHeader(); }
    if (index % 2 === 1) { pdf.setFillColor(247, 250, 252); pdf.rect(14, y, 183, 9, "F"); }
    pdf.setDrawColor(198, 211, 222);
    pdf.rect(14, y, 183, 9);
    pdf.setTextColor(23, 58, 85);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8);
    const values = [String(index + 1), `${result.lastName} ${result.firstName}`, result.apogeeCode, String(result.inscriptionNumber), result.finalGrade?.toFixed(2) ?? "-", result.resultStatus ?? "Pending"];
    let x = 14;
    values.forEach((value, valueIndex) => { if (valueIndex > 0) pdf.line(x, y, x, y + 9); pdf.text(value.slice(0, valueIndex === 1 ? 34 : 18), x + 1.5, y + 5.8); x += widths[valueIndex]; });
    y += 9;
  });
  listDocumentFooters(pdf, 210, 297);
  pdf.save(`final-results-${module.subjectModuleCode.toLowerCase()}.pdf`);
}

export async function saveAllFinalResultsPdf(results: FinalResult[], context: GradeDocumentContext) {
  if (!results.length) return;
  const { jsPDF } = await import("jspdf");
  const modules = Array.from(new Map(results.map((result) => [result.subjectModuleId, { id: result.subjectModuleId, code: result.subjectModuleCode }])).values());
  const students = Array.from(new Map(results.map((result) => [result.studentId, { id: result.studentId, name: `${result.lastName} ${result.firstName}`, apogee: result.apogeeCode }])).values());
  const resultByStudentModule = new Map(results.map((result) => [`${result.studentId}:${result.subjectModuleId}`, result]));
  const pdf = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
  listDocumentHeader(pdf, "Consolidated Final Results", context, `CR-${new Date().getFullYear()}`, 297);
  const studentWidth = 55;
  const apogeeWidth = 28;
  const moduleWidth = Math.min(27, (269 - studentWidth - apogeeWidth) / Math.max(modules.length, 1));
  let y = 88;
  const drawHeader = () => {
    pdf.setFillColor(23, 58, 85);
    pdf.rect(14, y, 269, 9, "F");
    pdf.setTextColor(255, 255, 255);
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(7.5);
    pdf.text("Student", 15.5, y + 5.8);
    pdf.text("Apogee", 14 + studentWidth + 1.5, y + 5.8);
    modules.forEach((module, index) => pdf.text(module.code.slice(0, 9), 14 + studentWidth + apogeeWidth + index * moduleWidth + 1.5, y + 5.8));
    y += 9;
  };
  drawHeader();
  students.forEach((student, studentIndex) => {
    if (y > 190) { pdf.addPage(); listDocumentHeader(pdf, "Consolidated Final Results", context, `CR-${new Date().getFullYear()}`, 297); y = 88; drawHeader(); }
    if (studentIndex % 2 === 1) { pdf.setFillColor(247, 250, 252); pdf.rect(14, y, 269, 9, "F"); }
    pdf.setDrawColor(198, 211, 222);
    pdf.rect(14, y, 269, 9);
    pdf.setTextColor(23, 58, 85);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(7.2);
    pdf.text(student.name.slice(0, 30), 15.5, y + 5.2);
    pdf.text(student.apogee.slice(0, 16), 14 + studentWidth + 1.5, y + 5.2);
    modules.forEach((module, index) => {
      const result = resultByStudentModule.get(`${student.id}:${module.id}`);
      pdf.text(result ? resultText(result) : "-", 14 + studentWidth + apogeeWidth + index * moduleWidth + 1.5, y + 5.2);
    });
    y += 9;
  });
  listDocumentFooters(pdf, 297, 210);
  pdf.save("final-results-all-modules.pdf");
}

export async function saveStudentFinalResultsPdf(results: FinalResult[], context: GradeDocumentContext, profile: Student) {
  if (!results.length) return;
  const { jsPDF } = await import("jspdf");
  const student = results[0];
  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  drawAcademicDocumentHeader(pdf, { academicLevel: context.academicLevel, academicYear: context.academicYear, apogeeCode: student.apogeeCode, cin: profile.cin, cne: profile.nationalStudentCode, context: context.label, firstName: student.firstName, lastName: student.lastName, program: context.program, programPath: context.programPath, reference: `FR-${student.apogeeCode}-${new Date().getFullYear()}`, semester: context.semester, title: "Final Academic Results" });
  const widths = [28, 92, 25, 28];
  let y = drawAcademicTableHeader(pdf, 111, ["Module", "Module title", "Grade / 20", "Result"], widths);
  results.forEach((result, index) => { y = drawAcademicTableRow(pdf, y, [result.subjectModuleCode, result.subjectModuleTitle, result.finalGrade?.toFixed(2) ?? "-", result.resultStatus ?? "Pending"], widths, index % 2 === 1); });
  drawAcademicDocumentClosing(pdf, y);
  addAcademicDocumentFooters(pdf);
  pdf.save(`${student.apogeeCode.toLowerCase()}-final-results.pdf`);
}
